/**
 * Generate 92 Trade Skill Modules tailored specifically to the given trade
 */
export function generateTradeSkillCurriculum(tradeId: string, tradeName: string): TradeSkillModule[] {
  const category = identifyTradeCategory(tradeName || tradeId);

  let sourceTopics: { phase: string; mod: string; task: string }[] = [];

  if (category === 'food') {
    sourceTopics = FOOD_BEVERAGE_TOPICS;
  } else if (category === 'electrical') {
    sourceTopics = ELECTRICAL_TOPICS;
  } else if (category === 'beauty') {
    return SHIKHON_92_DAYS.map(d => ({
      id: `tsm_${tradeId}_d${d.dayNumber}`,
      tradeId,
      dayNumber: d.dayNumber,
      moduleName: d.skillModule,
      taskNo: d.skillTaskNo,
      topic: d.skillTopic,
      theoryMinutes: d.skillTheoryMinutes,
      practicalMinutes: d.skillPracticalMinutes,
      totalMinutes: d.skillTotalMinutes,
      phaseGroup: d.phaseGroup,
      toolsRequired: d.notes,
      notes: '',
      createdAt: Date.now(),
      updatedAt: Date.now()
    }));
  } else {
    // Generic fallback based on trade name
    const cleanName = tradeName || 'কারিগরি ট্রেড';
    return Array.from({ length: 92 }, (_, i) => {
      const dayNum = i + 1;
      const phase = dayNum <= 15 ? 'মৌলিক সুরক্ষা ও টুলস' :
                    dayNum <= 45 ? 'তাত্ত্বিক ও বেসিক স্কিলস' :
                    dayNum <= 75 ? 'ব্যবহারিক ও প্রয়োগিক কাজ' : 'উন্নত কাজ ও প্রকল্প মূল্যায়ন';
      return {
        id: `tsm_${tradeId}_d${dayNum}`,
        tradeId,
        dayNumber: dayNum,
        moduleName: `${cleanName} - মডিউল ${toBn(Math.ceil(dayNum / 8))}`,
        taskNo: `কাজ ${toBn(dayNum)}`,
        topic: `${cleanName} বিষয়ক ব্যবহারিক দক্ষতা অনুশীলন ও কাজ #${toBn(dayNum)}`,
        theoryMinutes: 50,
        practicalMinutes: 70,
        totalMinutes: 120,
        phaseGroup: phase,
        toolsRequired: `${cleanName} টুলস ও সরঞ্জাম`,
        notes: '',
        createdAt: Date.now(),
        updatedAt: Date.now()
      };
    });
  }

  // Map source topics to 92 items
  return Array.from({ length: 92 }, (_, i) => {
    const dayNum = i + 1;
    const t = sourceTopics[i] || {
      phase: 'সাধারণ দক্ষতা',
      mod: `${tradeName} দক্ষতা অনুশীলন`,
      task: `${tradeName} বিষয়ক চূড়ান্ত ব্যবহারিক অনুশীলন ও রিভিশন #${toBn(dayNum)}`
    };

    return {
      id: `tsm_${tradeId}_d${dayNum}`,
      tradeId,
      dayNumber: dayNum,
      moduleName: t.mod,
      taskNo: `কাজ ${toBn(dayNum)}`,
      topic: t.task,
      theoryMinutes: 50,
      practicalMinutes: 70,
      totalMinutes: 120,
      phaseGroup: t.phase,
      toolsRequired: `${t.phase} সরঞ্জাম`,
      notes: '',
      createdAt: Date.now(),
      updatedAt: Date.now()
    };
  });
}

