// Helper to determine trade category from trade name or code
export function identifyTradeCategory(tradeNameOrCode: string): 'beauty' | 'food' | 'electrical' | 'computer' | 'tailoring' | 'general' {
  const s = (tradeNameOrCode || '').toLowerCase();
  if (s.includes('বিউটি') || s.includes('beauty') || s.includes('bc-')) return 'beauty';
  if (s.includes('ফুড') || s.includes('food') || s.includes('বেভারেজ') || s.includes('beverage') || s.includes('রান্না')) return 'food';
  if (s.includes('ইলেকট্রিক') || s.includes('electric') || s.includes('ইলেক্ট্রনিক') || s.includes('ওয়্যারিং') || s.includes('wiring')) return 'electrical';
  if (s.includes('কম্পিউটার') || s.includes('computer') || s.includes('গ্রাফিক্স') || s.includes('graphics')) return 'computer';
  if (s.includes('টেইলারিং') || s.includes('tailoring') || s.includes('সেলাই') || s.includes('পোশাক')) return 'tailoring';
  return 'general';
}

